def object_colour(png):
    """Nearest OBJECT_COLOURS entry to the median of the pixels that differ from the floor (partnet colour_of)."""
    import numpy as np
    from PIL import Image

    rgb = np.asarray(Image.open(png).convert("RGB")).reshape(-1, 3).astype(float)
    obj = rgb[np.abs(rgb - np.median(rgb, axis=0)).sum(1) > 60]
    c = np.median(obj if len(obj) >= 100 else rgb, axis=0)
    return min(OBJECT_COLOURS, key=lambda k: float(((np.array(OBJECT_COLOURS[k][0]) - c) ** 2).sum()))


FEATURES = (("door", "door", "门"), ("drawer", "drawer", "抽屉"), ("knob", "knob", "旋钮"), ("rack", "rack", "烤架"))


def names(root, manifest, previews):
    """object_names.json entries: category, the kind, colour + the kind, and colour, doors / drawers / knobs / racks
    and size in cm; clashes add the height, then depth, then the upstream model name."""
    from object_names import TABLE, load
    from partnet_mobility import COLOURS, COUNT_EN, COUNT_ZH, colour_of

    out = {}
    seen = {n for names in load(TABLE).values() for lang in ("en", "zh") for n in names[lang][-1:]}
    for entry in manifest["chosen"]:
        if entry["id"] in out:
            continue
        meta = json.loads((Path(root) / "Assets/Object/RoboDojo" / entry["id"] / "metadata.json").read_text())
        png = Path(previews) / entry["id"] / "preview" / "sim.png"
        if not png.is_file():
            continue
        rigid = entry.get("rigid")
        colour = object_colour(png) if rigid else colour_of(png)
        (cat_en, cat_zh), (kind_en, kind_zh) = (OBJECT_NAMES if rigid else KIND_NAMES)[entry["kind"]]
        parts = [] if rigid else [j["part"] for j in meta["body_joints"]]
        bits_en, bits_zh = [], []
        for part, en, zh in FEATURES:
            n = parts.count(part)
            if n:
                bits_en.append(f"{COUNT_EN.get(n, n)} {en}{'s' if n > 1 else ''}")
                bits_zh.append(f"{COUNT_ZH.get(n, n)}{zh}" if part == "door" else f"{n}个{zh}")
        w, d, h = (max(1, round(v * 100)) for v in meta["physics"]["size"])
        c_en, c_zh = colour, (OBJECT_COLOURS if rigid else COLOURS)[colour][1]
        tail_en = f" with {' and '.join(bits_en)}" if bits_en else ""
        head_zh = "、".join(bits_zh) + "的" if bits_zh else ""
        model = Path(entry["src"]).name
        for size_en, size_zh in (
            (f"{w} cm wide", f"{w}厘米宽"),
            (f"{w} by {h} cm", f"宽{w}高{h}厘米"),
            (f"{w} by {d} by {h} cm", f"宽{w}深{d}高{h}厘米"),
            (f"{model} {w} by {d} by {h} cm", f"{model}型宽{w}深{d}高{h}厘米"),
        ):
            detail_en = f"{size_en} {c_en} {kind_en}{tail_en}"
            detail_zh = f"{head_zh}{size_zh}{c_zh}{kind_zh}"
            if detail_en not in seen and detail_zh not in seen:
                break
        seen |= {detail_en, detail_zh}
        out[entry["id"]] = {
            "category": {"en": cat_en, "zh": cat_zh},
            "en": [kind_en, f"{c_en} {kind_en}", detail_en],
            "zh": [kind_zh, f"{c_zh}{kind_zh}", detail_zh],
        }
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("fetch", "select", "convert", "names", "ready"))
    parser.add_argument(
        "--previews", type=Path, help="names: the checks' --image-dir; ready: check_object.py's --image-dir"
    )
    parser.add_argument("--out", type=Path)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--root", type=Path)
    parser.add_argument("--manifest", type=Path)
    args = parser.parse_args()
    if args.command == "fetch":
        fetch(args.out)
    elif args.command == "select":
        result = select(args.source)
        args.manifest.write_text(json.dumps(result, indent=1, ensure_ascii=False) + "\n")
        print(f"chosen={len(result['chosen'])}, dropped={len(result['dropped'])}")
    elif args.command == "names":
        print(json.dumps(names(args.root, json.loads(args.manifest.read_text()), args.previews), ensure_ascii=False))
    elif args.command == "ready":
        result = ready(args.root, json.loads(args.manifest.read_text()), args.previews)
        print(f"runtime_ready={sum(result.values())} of {len(result)}")
    else:
        result = convert(args.root, json.loads(args.manifest.read_text()))
        out = args.root / "robocasa_conversion.json"
        out.write_text(json.dumps(result, indent=1) + "\n")
        print(f"converted={len(result['converted'])}, failed={len(result['failed'])} -> {out}")


if __name__ == "__main__":
    main()
